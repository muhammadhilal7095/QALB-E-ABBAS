// Internal linking + trustworthy external sources for every service page.
//
//   npm run links:build      (from the booking folder)
//
// Adds a "Related services & official sources" section just before each service page's final
// call-to-action. Related services come from the Services menu in assets/js/site-config.js
// (other services in the same category, plus a few useful cross-links); official sources come
// from scripts/official-sources.json. The block sits between <!-- LINKS:START --> and <!-- LINKS:END -->.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = join(HERE, "..", "..");
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(SITE, "assets/js/site-config.js"), "utf8"), sandbox);
const CFG = sandbox.window.SITE_CONFIG;
const sources = JSON.parse(readFileSync(join(HERE, "official-sources.json"), "utf8"));
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const icon = (n) => `<svg class="icon" aria-hidden="true"><use href="#i-${n}"></use></svg>`;

// Useful cross-links between categories (by page path).
const EXTRA = {
  ecommerce: ["/us-llc-formation", "/trademark-registration", "/university"],
  automation: ["/crm-development", "/social-media-marketing"],
  development: ["/seo", "/digital-marketing"],
  marketing: ["/website-development", "/shopify-development"],
  formation: ["/taxation", "/trademark-registration"],
  education: ["/malta-company-formation", "/university"],
  "real-estate": ["/digital-marketing", "/social-media-marketing", "/website-development", "/uae-company-formation"],
};
// Pages that are not in the Services menu but should link like a category.
const EXTRA_PAGES = { "/taxation": "formation", "/trademark-registration": "formation", "/tiktok-shop": "ecommerce" };

// Every service page in the menu: path -> { name, category }
const all = new Map();
for (const cat of CFG.services) for (const it of cat.items) {
  const path = it[2];
  if (!all.has(path)) all.set(path, { name: it[0], cat: cat.id, title: cat.title, icon: cat.icon });
}
const NAMES = { "/taxation": "US & UK Taxation", "/university": "Qalb-E-Abbas University", "/shopify-development": "Shopify Store Development", "/real-estate": "Real Estate in Pakistan" };
// Link text: the target page's own breadcrumb name (e.g. "US LLC Formation"), so links are descriptive.
const crumb = (p) => {
  try {
    const h = readFileSync(join(SITE, p.slice(1) + ".html"), "utf8");
    const m = h.match(/<li aria-current="page">([^<]+)<\/li>/);
    return m ? m[1].replace(/&amp;/g, "&") : "";
  } catch { return ""; }
};
const label = (p) => NAMES[p] || crumb(p) || (all.get(p) ? all.get(p).name : p.slice(1));
const iconFor = (p) => (all.get(p) ? all.get(p).icon : p === "/university" ? "graduation" : p === "/taxation" ? "receipt" : "shield");

let count = 0;
for (const file of readdirSync(SITE).filter((f) => f.endsWith(".html") && !f.startsWith("_"))) {
  const page = "/" + file.slice(0, -5);
  let html = readFileSync(join(SITE, file), "utf8");
  if (!/<li><a href="\/services">Services<\/a><\/li><li aria-current="page">/.test(html)) continue; // service pages only
  const cat = (all.get(page) || {}).cat || EXTRA_PAGES[page];
  if (!cat) continue;
  const same = [...all.entries()].filter(([p, v]) => v.cat === cat && p !== page).map(([p]) => p);
  const related = [...new Set([...same, ...(EXTRA[cat] || [])])].filter((p) => p !== page).slice(0, 6);
  const src = sources[page.slice(1)] || [];

  const rel = related.map((p) => `<li><a href="${p}"><span class="rl__icon">${icon(iconFor(p))}</span><span>${esc(label(p))}</span>${icon("arrow-right")}</a></li>`).join("");
  const off = src.map(([t, u]) => `<li><a href="${esc(u)}" target="_blank" rel="noopener">${icon("globe")}<span>${esc(t)}</span><span class="sr-only"> (opens in a new tab)</span></a></li>`).join("");
  const block = `<!-- LINKS:START — generated by booking/scripts/build-links.mjs; run \`npm run links:build\` -->
    <section class="section rl" aria-labelledby="rl-title">
      <div class="container">
        <div class="rl__grid${off ? "" : " rl__grid--single"}">
          <div class="rl__col">
            <h2 id="rl-title" class="rl__title">Related services</h2>
            <ul class="rl__links">${rel}</ul>
          </div>${off ? `
          <aside class="rl__col rl__src" aria-label="Official sources">
            <h2 class="rl__title">Official sources</h2>
            <p class="rl__note">Rules and fees change — check the official guidance:</p>
            <ul class="rl__ext">${off}</ul>
          </aside>` : ""}
        </div>
      </div>
    </section>
    <!-- LINKS:END -->`;

  if (html.includes("<!-- LINKS:START")) html = html.replace(/<!-- LINKS:START[\s\S]*?<!-- LINKS:END -->/, () => block);
  else {
    const i = html.lastIndexOf('<section class="section" aria-label="Get started">');
    if (i < 0) { console.warn(`${file}: no final call-to-action section found`); continue; }
    html = html.slice(0, i) + block + "\n    " + html.slice(i);
  }
  writeFileSync(join(SITE, file), html);
  count++;
}
console.log(`Related services & official sources added to ${count} service pages.`);
