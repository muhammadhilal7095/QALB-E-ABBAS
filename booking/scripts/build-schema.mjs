// Adds schema.org structured data (JSON-LD) to every page of the website.
//
//   npm run schema:build      (from the booking folder; re-run after changing pages or social links)
//
// Each page gets: the business (ProfessionalService) with contact details and social profiles
// from assets/js/site-config.js, a BreadcrumbList from the page's breadcrumb, a Service on
// service pages, a FAQPage where the page has FAQs, and WebSite on the homepage.
// The block sits between <!-- SCHEMA:START --> and <!-- SCHEMA:END --> before </head>.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
// The live website address. Change it here if the site uses a different domain.
const SITE_URL = "https://www.qalbeabbas.com";

// Social profiles: read from assets/js/site-config.js (social: { facebook: "…", … }).
const cfg = readFileSync(join(SITE, "assets/js/site-config.js"), "utf8");
const socialBlock = (cfg.match(/social:\s*\{([\s\S]*?)\}/) || [, ""])[1];
const sameAs = [...socialBlock.matchAll(/:\s*"(https?:\/\/[^"]+)"/g)].map((m) => m[1]);

const ORG_ID = `${SITE_URL}/#organization`;
const DAY = ["", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
const avail = JSON.parse(readFileSync(join(SITE, "booking/src/lib/service-catalog.json"), "utf8")).availability;
const hours = { days: avail.days.map((d) => DAY[d]), start: avail.start, end: avail.end };
const org = {
  "@type": "ProfessionalService",
  "@id": ORG_ID,
  name: "Qalb-E-Abbas",
  url: `${SITE_URL}/`,
  logo: `${SITE_URL}/assets/img/logo.svg`,
  image: `${SITE_URL}/assets/img/hero/amazon-seller.jpg`,
  description: "E-commerce growth services, company formation for non-residents, tax filing, digital marketing and Qalb-E-Abbas University training.",
  email: "contact@qalbeabbas.com",
  address: { "@type": "PostalAddress", addressLocality: "Oldham", addressRegion: "Greater Manchester", addressCountry: "GB" },
  areaServed: ["GB", "US", "MT", "AE", "PK"],
  // Opening hours = the consultation booking hours in service-catalog.json (availability).
  openingHoursSpecification: [{ "@type": "OpeningHoursSpecification", dayOfWeek: hours.days, opens: hours.start, closes: hours.end }],
  contactPoint: [{ "@type": "ContactPoint", contactType: "customer service", email: "contact@qalbeabbas.com", availableLanguage: ["English", "Urdu"] }],
  ...(sameAs.length ? { sameAs } : {}),
};

const decode = (s) => s.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&#39;|&rsquo;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/\s+/g, " ").trim();
const START = "<!-- SCHEMA:START — generated by booking/scripts/build-schema.mjs; run `npm run schema:build` -->";
const END = "<!-- SCHEMA:END -->";

let count = 0;
for (const file of readdirSync(SITE).filter((f) => f.endsWith(".html") && !f.startsWith("_"))) {
  let html = readFileSync(join(SITE, file), "utf8");
  const url = file === "index.html" ? `${SITE_URL}/` : `${SITE_URL}/${file.replace(/\.html$/, "")}`;
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/) || [, ""])[1]);
  const desc = decode((html.match(/<meta name="description" content="([^"]*)"/) || [, ""])[1]);
  const graph = [org];

  if (file === "index.html") {
    graph.push({ "@type": "WebSite", "@id": `${SITE_URL}/#website`, url: `${SITE_URL}/`, name: "Qalb-E-Abbas", publisher: { "@id": ORG_ID }, inLanguage: "en-GB" });
  }

  // Breadcrumbs from <ol class="breadcrumb …">
  const bc = html.match(/<ol class="breadcrumb[^"]*"[^>]*>([\s\S]*?)<\/ol>/);
  if (bc) {
    const items = [...bc[1].matchAll(/<li[^>]*>([\s\S]*?)<\/li>/g)].map((li, i, all) => {
      const a = li[1].match(/href="([^"]+)"/);
      const name = decode(li[1]);
      const href = a ? (a[1] === "/" ? `${SITE_URL}/` : `${SITE_URL}${a[1].startsWith("/") ? "" : "/"}${a[1].replace(/\.html$/, "")}`) : url;
      return { "@type": "ListItem", position: i + 1, name, item: i === all.length - 1 ? url : href };
    }).filter((x) => x.name);
    if (items.length > 1) graph.push({ "@type": "BreadcrumbList", itemListElement: items });
    // Service pages: breadcrumb Home / Services / <service>
    if (items.length === 3 && items[1].name === "Services") {
      graph.push({ "@type": "Service", name: items[2].name, serviceType: items[2].name, description: desc, url, provider: { "@id": ORG_ID }, areaServed: org.areaServed });
    }
  }

  // FAQs: <details><summary>Question</summary><div>Answer</div></details>
  const faqs = [...html.matchAll(/<details[^>]*>\s*<summary[^>]*>([\s\S]*?)<\/summary>\s*<div[^>]*>([\s\S]*?)<\/div>\s*<\/details>/g)]
    .map((m) => ({ q: decode(m[1]), a: decode(m[2]) })).filter((x) => x.q && x.a);
  if (faqs.length) {
    graph.push({ "@type": "FAQPage", mainEntity: faqs.map((f) => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })) });
  }

  // The page's main photo (first photo in <main>) as an ImageObject, with its alt text as the caption.
  const mainHtml = html.slice(html.indexOf("<main"));
  const photo = mainHtml.match(/<img[^>]+src="(assets\/img\/[^"]+\.(?:jpe?g|png|webp))"[^>]*>/);
  const primaryImage = photo ? {
    "@type": "ImageObject",
    url: `${SITE_URL}/${photo[1].replace(/\.webp$/, ".jpg")}`,
    caption: decode((photo[0].match(/\balt="([^"]*)"/) || [, ""])[1]),
    ...(photo[0].match(/\bwidth="(\d+)"/) ? { width: Number(photo[0].match(/\bwidth="(\d+)"/)[1]) } : {}),
    ...(photo[0].match(/\bheight="(\d+)"/) ? { height: Number(photo[0].match(/\bheight="(\d+)"/)[1]) } : {}),
  } : null;

  // Articles: pages with a byline (<p class="byline">) and <time datetime> published/updated dates.
  const byline = html.match(/<p class="byline">([\s\S]*?)<\/p>/);
  if (byline) {
    const times = [...byline[1].matchAll(/<time datetime="([^"]+)"/g)].map((m) => m[1]);
    const h1 = decode((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, title])[1]);
    graph.push({
      "@type": "BlogPosting", "@id": `${url}#article`, headline: h1.slice(0, 110), description: desc, url,
      mainEntityOfPage: { "@id": `${url}#webpage` },
      ...(times[0] ? { datePublished: times[0] } : {}), ...(times[1] || times[0] ? { dateModified: times[1] || times[0] } : {}),
      author: { "@type": "Organization", name: "Qalb-E-Abbas Team", url: `${SITE_URL}/team` },
      publisher: { "@id": ORG_ID },
      ...(primaryImage ? { image: primaryImage.url } : {}), inLanguage: "en-GB",
    });
  }

  graph.push({ "@type": "WebPage", "@id": `${url}#webpage`, url, name: title, description: desc, isPartOf: { "@id": `${SITE_URL}/#website` }, about: { "@id": ORG_ID }, ...(primaryImage ? { primaryImageOfPage: primaryImage } : {}) });

  const json = JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/</g, "\\u003c");
  const block = `${START}\n  <script type="application/ld+json">\n${json}\n  </script>\n  ${END}`;
  if (html.includes("<!-- SCHEMA:START")) html = html.replace(/<!-- SCHEMA:START[\s\S]*?<!-- SCHEMA:END -->/, block);
  else html = html.replace("</head>", `  ${block}\n</head>`);
  writeFileSync(join(SITE, file), html);
  count++;
}
console.log(`Schema added to ${count} pages${sameAs.length ? ` (${sameAs.length} social profiles)` : " (no social profiles set yet in site-config.js)"}.`);
